<#
.SYNOPSIS
  Build Al-Jazari's Flash 8 fixtures end to end with the real Flash 8 IDE.

.DESCRIPTION
  For each fixture NAME given with -Names (or every builder with -All):
    1. writes <WorkDir>\gen\NAME.jsfl: a short prelude that defines the paths
       (JZ_OUT, JZ_SRC, JZ_LOG, JZ_WORK as file:/// URIs) followed by the
       builder fixtures\NAME.jsfl (make-smoke.jsfl for "smoke");
    2. runs it in Flash 8 through run-jsfl.ps1, which takes the Flash lock.
       The builder saves <OutRoot>\NAME\NAME.fla, reopens it and publishes
       <OutRoot>\NAME\flash8.swf (default profile: Player 8, AS2, compressed);
       its step log is <WorkDir>\logs\NAME.log;
    3. converts the FLA to <OutRoot>\NAME\xfl with JPEXS FLA Convert (the old
       xfl folder is removed first; JPEXS refuses an existing folder);
    4. unless -SkipTrace, records Flash 8's Test Movie output with
       capture-trace.ps1 into <OutRoot>\NAME\flash8-trace.txt.
  The source assets in -SrcDir (tests\fixtures\_src) are regenerated only when
  missing (make-images.py, make-gradient-swf.py).  Flash runs strictly one
  instance at a time (target\flash8.lock, see flash-lock.ps1).

  Rebuilding a committed fixture replaces its truth files; do that only on
  purpose.  -OutRoot lets you build into a scratch folder instead.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File C:\dev\jazari\tools\oracle\build-all.ps1 -Names groups
  powershell -NoProfile -ExecutionPolicy Bypass -File C:\dev\jazari\tools\oracle\build-all.ps1 -Names gradients,symbols -SkipTrace -OutRoot C:\dev\jazari\target\oracle\scratch
#>
param(
    [string[]] $Names = @(),
    [switch] $All,
    [switch] $SkipTrace,
    [string] $OutRoot = '',
    [string] $SrcDir = '',
    [string] $WorkDir = '',
    [int] $PlaySec = 0,
    [int] $TimeoutSec = 180,
    [string] $Java = '',
    [string] $Jar = 'C:\dev\tools\jpexs-fla-convert-3.0.0\fla_convert.jar'
)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'flash-lock.ps1')
$repo = Get-JazariRoot
if (-not $OutRoot) { $OutRoot = Join-Path $repo 'tests\fixtures' }
if (-not $SrcDir) { $SrcDir = Join-Path $repo 'tests\fixtures\_src' }
if (-not $WorkDir) { $WorkDir = Join-Path $repo 'target\oracle' }
if (-not $Java) {
    $cmd = Get-Command java -ErrorAction SilentlyContinue
    $Java = if ($cmd) { $cmd.Source } else { 'C:\Program Files\Eclipse Adoptium\jdk-21.0.12.101-hotspot\bin\java.exe' }
}

function Get-Builder([string] $n) {
    if ($n -eq 'smoke') { return Join-Path $PSScriptRoot 'make-smoke.jsfl' }
    return Join-Path $PSScriptRoot "fixtures\$n.jsfl"
}

# "-Names a,b" arrives as one string when the script is started with -File
$Names = @($Names | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim() } | Where-Object { $_ })
if ($All) {
    $Names = @(Get-ChildItem -LiteralPath (Join-Path $PSScriptRoot 'fixtures') -Filter *.jsfl | ForEach-Object { $_.BaseName }) + @('smoke')
}
if ($Names.Count -eq 0) { throw 'name the fixtures to build with -Names a,b (or -All to rebuild every fixture)' }
foreach ($n in $Names) { if (-not (Test-Path -LiteralPath (Get-Builder $n))) { throw "unknown fixture: $n (no builder)" } }

# Default Test Movie play time per fixture (seconds); -PlaySec overrides.
$play = @{ 'tweens' = 5; 'as2' = 5; 'masks' = 4; 'scenes' = 5 }

$genDir = Join-Path $WorkDir 'gen'
$logDir = Join-Path $WorkDir 'logs'
New-Item -ItemType Directory -Force $genDir, $logDir, $OutRoot | Out-Null
if (-not (Test-Path (Join-Path $SrcDir 'alpha-disc.png')) -or -not (Test-Path (Join-Path $SrcDir 'bars.jpg'))) {
    & python -I (Join-Path $PSScriptRoot 'make-images.py') $SrcDir
}
if (-not (Test-Path (Join-Path $SrcDir 'grad-src.swf'))) {
    & python -I (Join-Path $PSScriptRoot 'make-gradient-swf.py') (Join-Path $SrcDir 'grad-src.swf')
}

$summary = @()
foreach ($n in $Names) {
    Write-Host "=================== $n ==================="
    $dir = Join-Path $OutRoot $n
    New-Item -ItemType Directory -Force $dir | Out-Null
    $log = Join-Path $logDir "$n.log"
    $prelude = @(
        "// Generated by tools/oracle/build-all.ps1 from $(Split-Path -Leaf (Get-Builder $n)); do not edit.",
        "var JZ_OUT = `"$(ConvertTo-FileUri $dir)/`";",
        "var JZ_SRC = `"$(ConvertTo-FileUri $SrcDir)/`";",
        "var JZ_LOG = `"$(ConvertTo-FileUri $log)`";",
        "var JZ_WORK = `"$(ConvertTo-FileUri $logDir)/`";",
        ''
    ) -join "`r`n"
    $gen = Join-Path $genDir "$n.jsfl"
    # Byte copy of the builder (keep builders ASCII: Flash 8 reads JSFL in the system code page).
    [byte[]] $bytes = [System.Text.Encoding]::ASCII.GetBytes($prelude) + [System.IO.File]::ReadAllBytes((Get-Builder $n))
    [System.IO.File]::WriteAllBytes($gen, $bytes)

    & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'run-jsfl.ps1') `
        -Script $gen -Log $log -TimeoutSec $TimeoutSec
    $build = $LASTEXITCODE
    $failed = (Select-String -LiteralPath $log -Pattern '^FAILED STEPS: (\d+)' -ErrorAction SilentlyContinue |
               ForEach-Object { $_.Matches[0].Groups[1].Value }) -join ''
    if ($build -ne 0 -or -not (Test-Path (Join-Path $dir "$n.fla"))) { $summary += "$n : BUILD FAILED (launcher exit $build)"; continue }

    $xfl = Join-Path $dir 'xfl'
    if (Test-Path $xfl) { Remove-Item -Recurse -Force $xfl }
    # java prints to stderr; under 'Stop' PowerShell 5.1 would turn that into a terminating error
    $ErrorActionPreference = 'Continue'
    $conv = & $Java -jar $Jar convert --format CS5 --container xfl --charset WINDOWS-1256 (Join-Path $dir "$n.fla") $xfl 2>&1 |
            ForEach-Object { "$_" } | Select-Object -Last 1
    $ErrorActionPreference = 'Stop'
    Write-Host "JPEXS: $conv"

    $trace = '-'
    if (-not $SkipTrace) {
        $sec = if ($PlaySec -gt 0) { $PlaySec } elseif ($play.ContainsKey($n)) { $play[$n] } else { 3 }
        Remove-Item -LiteralPath (Join-Path $dir 'flash8-trace.txt') -ErrorAction SilentlyContinue
        & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'capture-trace.ps1') `
            -Name $n -PlaySec $sec -FixturesRoot $OutRoot -WorkDir (Join-Path $WorkDir 'tracecap') | Out-Null
        $tf = Join-Path $dir 'flash8-trace.txt'
        $trace = if (Test-Path $tf) { "$((Get-Content $tf | Measure-Object -Line).Lines) trace line(s)" } else { 'no trace captured' }
    }
    $summary += "$n : failed JSFL steps=$failed, JPEXS=$conv, trace=$trace"
}
Write-Host '=================== summary ==================='
$summary | ForEach-Object { Write-Host $_ }
